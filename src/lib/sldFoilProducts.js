/** A Scryfall card's Secret Lair foil product (decision 510), or null: only for a card that has a foil finish. */
const productOf = (card) => ((card?.finishes ?? []).includes('foil') && SLD_FOIL_PRODUCTS[String(card.tcgplayer_id)]) || null;

const lower = (v) => String(v ?? '').toLowerCase();

/** The JustTCG lookup for a Scryfall card's Secret Lair foil product, or null (decision 510). Pure. */
export function sldFoilLookup(card) {
  const id = productOf(card);
  return id ? { key: `mtg:sldfoil:${id}`, game: 'mtg', lang: 'en', tcgplayerId: id } : null;
}

/**
 * The foil's prices for a card with a Secret Lair foil product (decision 510): the main card's when it lists
 * a foil (as a surge foil's are), else the foil product's; undefined when the card has none, for the usual way.
 * Pure.
 */
export function sldFoilResult(card, results, finish) {
  const id = productOf(card);
  if (finish !== 'foil' || !id) return undefined;
  const main = results[`mtg:scryfall:${card.id}`];
  const foilOnMain = main?.card?.variants?.some((v) => lower(v.printing).includes('foil') && !lower(v.printing).includes('etched'));
  if (foilOnMain) return main;
  return results[`mtg:sldfoil:${id}`] ?? main;
}

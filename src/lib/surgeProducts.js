const lower = (v) => String(v ?? '').toLowerCase();

/** The JustTCG lookup for a Scryfall card's surge foil product, or null (decision 316). Pure. */
export function surgeLookup(card) {
  const id = SURGE_PRODUCTS[card?.id];
  if (!id || !(card.finishes ?? []).includes('foil')) return null;
  return { key: `mtg:surge:${id}`, game: 'mtg', lang: 'en', tcgplayerId: id };
}

/**
 * The foil's prices for a card with a surge foil product (decision 316): the
 * main card's when it lists a foil (as an etched printing's are), else the
 * surge foil product's; undefined when the card has none, for the usual way.
 * Pure.
 */
export function surgeResult(card, results, finish) {
  const id = SURGE_PRODUCTS[card?.id];
  if (finish !== 'foil' || !id) return undefined;
  const main = results[`mtg:scryfall:${card.id}`];
  const foilOnMain = main?.card?.variants?.some((v) => lower(v.printing).includes('foil') && !lower(v.printing).includes('etched'));
  if (foilOnMain) return main;
  return results[`mtg:surge:${id}`] ?? main;
}
